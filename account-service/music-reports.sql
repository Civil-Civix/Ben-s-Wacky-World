CREATE TABLE IF NOT EXISTS music_reports (
 id INTEGER PRIMARY KEY AUTOINCREMENT, song_id TEXT NOT NULL, reporter TEXT NOT NULL REFERENCES users(id),
 kind TEXT NOT NULL, note TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'open', created INTEGER NOT NULL,
 UNIQUE(song_id,reporter)
);
CREATE TABLE IF NOT EXISTS music_blocks (song_id TEXT PRIMARY KEY, actor TEXT NOT NULL, reason TEXT NOT NULL, created INTEGER NOT NULL);
